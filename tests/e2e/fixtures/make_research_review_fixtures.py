"""Write API responses for the research review browser test.

Every response comes from the real FastAPI app running on a visibly synthetic case and a
synthetic archived prediction (the same inputs as apps/api/tests/test_research_review.py).
Nothing is hand-written. Rerun after an API change:

    apps/api/.venv/Scripts/python.exe tests/e2e/fixtures/make_research_review_fixtures.py
"""
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'apps' / 'api'))
sys.path.insert(0, str(ROOT / 'apps' / 'api' / 'tests'))
OUT = Path(__file__).with_name('research-review-fixtures.json')
PREDICTION = b',data\n0,18\n1,25\n3,41\n'
CASE_ID = 'openkbp:test-synthetic-case'


def _sparse(path: Path, items, binary=False):
    path.write_text(',data\n' + ''.join(f'{i},{"" if binary else value}\n' for i, value in items), encoding='utf8')


def main():
    tmp = Path(tempfile.mkdtemp(prefix='medforge-review-fixtures-'))
    case = tmp / 'test-synthetic-case'
    case.mkdir()
    (case / 'voxel_dimensions.csv').write_text('2.0\n2.0\n2.0\n', encoding='utf8')
    _sparse(case / 'ct.csv', [(0, 100), (1, 200)])
    _sparse(case / 'dose.csv', [(0, 12), (1, 22), (3, 40)])
    _sparse(case / 'possible_dose_mask.csv', [(0, 0), (1, 0), (3, 0)], binary=True)
    _sparse(case / 'Brainstem.csv', [(0, 0), (1, 0)], binary=True)
    os.environ.update({'MEDFORGE_OPENKBP_CASE_DIR': str(case), 'MEDFORGE_DB_PATH': str(tmp / 'fixtures.sqlite3'),
                       'MEDFORGE_DOSE_ARTIFACT_DIR': str(tmp / 'dose-artifacts'), 'MEDFORGE_SOURCE_KIND': 'benchmark'})
    for key in ('MEDFORGE_ENDOSCAPES_ROOT', 'MEDFORGE_FISAV_ROOT'):
        os.environ.pop(key, None)

    from fastapi.testclient import TestClient
    from app.main import create_app
    from helpers import TEST_PASSWORD, provision_user

    client = TestClient(create_app())
    # An educator prepares the import; only a Clinical Reviewer (or admin) may review.
    provision_user('preparer', 'educator')
    preparer = client.post('/api/v1/auth/local-login', json={'username': 'preparer', 'password': TEST_PASSWORD}).json()
    provision_user('reviewer', 'clinical_reviewer')
    login = client.post('/api/v1/auth/local-login', json={'username': 'reviewer', 'password': TEST_PASSWORD})
    session = login.json()
    headers = {'Authorization': f"Bearer {session['access_token']}"}
    imported = client.put(f'/api/v1/cases/{CASE_ID}/dose-artifacts?file_name=prediction.csv', content=PREDICTION, headers={
        'Authorization': f"Bearer {preparer['access_token']}", 'Content-Type': 'text/csv', 'X-Dose-Origin': 'archived_model_prediction', 'X-Dose-Model-Revision': 'synthetic-model@test',
        'X-Dose-Source-Revision': 'synthetic-archive@test', 'X-Dose-Rights-Basis': 'Synthetic test fixture', 'X-Dose-Source-Case': CASE_ID,
        'X-Dose-Rights-Confirmed': 'true', 'X-Dose-Unit': 'Gy', 'X-Dose-Index-Convention': 'x-major-y-middle-z-fastest',
        'X-Dose-Array-Shape': '128,128,128', 'X-Dose-Spacing-MM': '2,2,2', 'X-Dose-File-SHA256': hashlib.sha256(PREDICTION).hexdigest()})
    imported.raise_for_status()
    artifact_id = imported.json()['id']
    base = f'/api/v1/cases/{CASE_ID}/dose-artifacts'

    def get(path):
        response = client.get(path, headers=headers)
        response.raise_for_status()
        return response.json()

    created = client.post('/api/v1/research-reviews', headers=headers, json={
        'case_id': CASE_ID, 'artifact_id': artifact_id, 'roi': 'Brainstem', 'decision': 'request_revision',
        'rationale': 'Brainstem mean dose differs from the reference.', 'axis': 2, 'index': 1, 'voxel': [0, 0, 1]})
    created.raise_for_status()
    review = created.json()
    fixtures = {
        'note': 'Generated by make_research_review_fixtures.py from the real API on a synthetic case. Not patient data.',
        'case_id': CASE_ID,
        'artifact_id': artifact_id,
        'session': {key: session[key] for key in session if key != 'access_token'} | {'access_token': 'fixture-token'},
        'me': get('/api/v1/auth/me'),
        'artifacts': get(base),
        'comparison': get(f'{base}/{artifact_id}/comparison'),
        'slice': get(f'{base}/{artifact_id}/slice?axis=2&index=1'),
        'voxel': get(f'{base}/{artifact_id}/voxel?x=0&y=0&z=1'),
        'review': review,
        'review_export': get(f"/api/v1/research-reviews/{review['id']}/export"),
        'review_fhir': get(f"/api/v1/research-reviews/{review['id']}/fhir"),
    }
    OUT.write_text(json.dumps(fixtures, indent=1, sort_keys=True) + '\n', encoding='utf8', newline='\n')
    print(f'Wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
