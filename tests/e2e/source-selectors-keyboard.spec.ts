import { expect, test } from '@playwright/test'

test('keyboard-only source selection, Escape, and focus work with installed research records @source', async ({ page }) => {
  test.setTimeout(90_000)
  const educatorUsername = process.env.MEDFORGE_E2E_RESEARCH_USERNAME
  const educatorPassword = process.env.MEDFORGE_E2E_RESEARCH_PASSWORD
  expect(educatorUsername && educatorPassword, 'Set credentials for an educator in the disposable source profile').toBeTruthy()

  // Global case search is backed by the installed case registry, not a fixture.
  await page.goto('/studio/fistulaguard/cases/fisav%3Apat001')
  const globalTrigger = page.getByRole('button', { name: 'Find a research case or workspace' })
  await globalTrigger.click()
  const globalInput = page.getByRole('combobox', { name: 'Search cases, datasets, specialties, and workspaces' })
  await globalInput.fill('pat001')
  const globalOption = page.getByRole('option', { name: /pat001/ }).first()
  await expect(globalOption).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Find a research case or workspace' })).toBeHidden()
  await expect(globalTrigger).toBeFocused()
  await expect(page).toHaveURL(/fisav%3Apat001/i)
  await globalTrigger.click()
  await page.getByRole('combobox', { name: 'Search cases, datasets, specialties, and workspaces' }).fill('pat011')
  await expect(page.getByRole('option', { name: /pat011/ }).first()).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/fisav%3Apat011/i)
  await expect(page.getByRole('heading', { name: 'FiSaV · pat011 · source signal' })).toBeVisible()

  // The dedicated FiSaV combobox selects by source ID and Escape cancels a new query without changing route.
  const signalPicker = page.getByRole('combobox', { name: 'Search installed FiSaV recordings' })
  await signalPicker.fill('pat001')
  await expect(page.getByRole('option', { name: 'pat001', exact: true })).toBeVisible()
  await signalPicker.press('Escape')
  await expect(page.getByRole('option', { name: 'pat001', exact: true })).toHaveCount(0)
  await expect(signalPicker).toBeFocused()
  await expect(page).toHaveURL(/fisav%3Apat011/i)
  await signalPicker.fill('pat001')
  await signalPicker.press('ArrowDown')
  await signalPicker.press('Enter')
  await expect(page).toHaveURL(/fisav%3Apat001/i)
  await expect(page.getByRole('heading', { name: 'FiSaV · pat001 · source signal' })).toBeVisible()

  // SurgiVision resolves a real annotated frame with keyboard-only search and commit.
  await page.goto('/studio/surgivision/cases/endoscapes%3Atest%3A162_6575')
  await page.getByRole('tab', { name: 'Annotated stills' }).click()
  const framePicker = page.getByRole('combobox', { name: 'Jump to surgical frame by split, video, or frame number' })
  await framePicker.fill('test video 163 frame 52925')
  await expect(page.getByRole('option', { name: /test.*video 163.*frame 52925.*endoscapes:test:163_52925/i })).toBeVisible()
  await framePicker.press('ArrowDown')
  await framePicker.press('Enter')
  await expect(page).toHaveURL(/endoscapes%3Atest%3A163_52925/i)
  await page.getByRole('tab', { name: 'Annotated stills' }).click()
  const selectedFramePicker = page.getByRole('combobox', { name: 'Jump to surgical frame by split, video, or frame number' })
  await selectedFramePicker.fill('test video 162 frame 6575')
  await expect(page.getByRole('option', { name: /test.*video 162.*frame 6575.*endoscapes:test:162_6575/i })).toBeVisible()
  await selectedFramePicker.press('Escape')
  await expect(page.getByRole('option', { name: /frame 6575.*endoscapes:test:162_6575/i })).toHaveCount(0)
  await expect(selectedFramePicker).toBeFocused()
  await expect(page).toHaveURL(/endoscapes%3Atest%3A163_52925/i)

  // The Educator picker follows the same keyboard contract while retaining its source selection.
  await page.goto('/educator')
  await page.getByLabel('Username').fill(educatorUsername!)
  await page.getByLabel('Password').fill(educatorPassword!)
  const login = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/v1/auth/local-login')
  await page.getByRole('button', { name: 'Sign in as educator' }).click()
  expect((await login).ok()).toBeTruthy()
  await page.getByRole('button', { name: 'Create case lesson' }).click()
  const educatorPicker = page.getByRole('combobox', { name: /Research source; search by case/ })
  await educatorPicker.fill('test video 162 frame 6575')
  await expect(page.getByRole('option', { name: /Endoscapes test.*frame 6575.*video-162:frame-6575/i })).toBeVisible()
  await educatorPicker.press('ArrowDown')
  await educatorPicker.press('Enter')
  await expect(educatorPicker).toHaveValue(/test.*video 162.*frame 6575/i)
  await educatorPicker.fill('test video 163 frame 52925')
  await expect(page.getByRole('option', { name: /Endoscapes test.*frame 52925.*video-163:frame-52925/i })).toBeVisible()
  await educatorPicker.press('Escape')
  await expect(page.getByRole('option', { name: /frame 52925.*video-163:frame-52925/i })).toHaveCount(0)
  await expect(educatorPicker).toBeFocused()
  await expect(educatorPicker).toHaveValue(/test.*video 162.*frame 6575/i)
})
