"""Deterministic, local-only DoseTwin water-cylinder phantom.

This is synthetic geometry for software demonstration. It contains no patient
anatomy and is not a treatment plan or an inference result.
"""
from __future__ import annotations

import hashlib
from functools import lru_cache

import numpy as np

CASE_ID = 'synthetic-dose:phantom-v1'
DATASET_ID = 'medforge-synthetic-phantom'
SOURCE_CASE_ID = 'phantom-v1'
SOURCE_REVISION = 'medforge-synthetic-phantom-v1'
SHAPE = (128, 128, 128)
SPACING_MM = (2.5, 2.5, 2.5)
STRUCTURES = ('Target', 'OAR-Cylinder-A', 'OAR-Cylinder-B')
NOTICE = 'SYNTHETIC PHANTOM · NOT ANATOMY · NOT A TREATMENT PLAN'
LIMITATIONS = [
    NOTICE,
    'Deterministic analytic geometry and dose field; no medical images, patients, labels, or model inference.',
    'The 2.5 mm voxel spacing is illustrative and is not patient geometry.',
    'Dose values use an arbitrary synthetic illustrative scale, not physical Gy calibration. Dose and ROI summaries are not benchmark metrics or clinical evaluations.',
]


@lru_cache(maxsize=4)
def volume(name: str) -> np.ndarray:
    """Return one immutable float32 128-cube volume in x,y,z storage order."""
    if name not in {'ct', 'dose', *STRUCTURES}:
        raise ValueError('Unknown synthetic phantom volume')
    axis = np.arange(128, dtype=np.float32)
    x = axis[:, None, None]
    y = axis[None, :, None]
    z = axis[None, None, :]
    radial_xy_sq = (x - 63.5) ** 2 + (y - 63.5) ** 2
    water = radial_xy_sq <= 54.0 ** 2

    if name == 'ct':
        result = np.broadcast_to(water, SHAPE).astype(np.float32)
    elif name == 'Target':
        result = (((x - 64) ** 2 + (y - 64) ** 2 + (z - 64) ** 2) <= 11 ** 2).astype(np.float32)
    elif name == 'OAR-Cylinder-A':
        result = np.broadcast_to(((x - 40) ** 2 + (y - 64) ** 2) <= 7 ** 2, SHAPE).astype(np.float32)
    elif name == 'OAR-Cylinder-B':
        result = np.broadcast_to(((x - 88) ** 2 + (y - 64) ** 2) <= 7 ** 2, SHAPE).astype(np.float32)
    else:
        radius = np.sqrt((x - 64) ** 2 + (y - 64) ** 2 + (z - 64) ** 2)
        outside_target = np.maximum(radius - 11.0, 0.0)
        result = (70.0 * np.exp(-((outside_target / 24.0) ** 2)) * water).astype(np.float32)

    result.setflags(write=False)
    return result


@lru_cache(maxsize=4)
def volume_sha256(name: str) -> str:
    values = volume(name)
    # Explicit little-endian serialization keeps hashes stable across hosts.
    return hashlib.sha256(values.astype('<f4', copy=False).tobytes(order='C')).hexdigest()


