def slice_values(name: str, axis: int, index: int) -> tuple[list[float], tuple[int, int]]:
    plane = np.take(volume(name), index, axis=axis)
    return plane.ravel(order='C').tolist(), (int(plane.shape[0]), int(plane.shape[1]))


def dvh(roi: str) -> dict:
    dose = volume('dose').astype(np.float64, copy=False)
    mask = volume(roi).astype(bool, copy=False)
    values = dose[mask]
    if not values.size:
        raise ValueError('Synthetic structure is empty')
    spacing = np.asarray(SPACING_MM, dtype=np.float64)
    volume_cc = float(np.prod(spacing) / 1000.0)
    dose_max = float(np.max(dose))
    thresholds = np.linspace(0.0, dose_max, 51)
    return {
        'voxel_count': int(values.size),
        'mean_dose_gy': float(np.mean(values)),
        'dose_display_max_gy': dose_max,
        'spacing_mm': SPACING_MM,
        'ct_display_range': (0.0, 1.0),
        'ct_display_note': 'Synthetic relative water-density values from 0 to 1; not CT Hounsfield units. Dose values use an arbitrary synthetic illustrative scale, not physical Gy calibration.',
        'official_metrics': {
            'volume_cc': float(values.size * volume_cc),
            'dmean_gy': float(np.mean(values)),
            'dmax_voxel_gy': float(np.max(values)),
            'd95_gy_interpolated': float(np.percentile(values, 5)),
            'd0_1cc_gy_openkbp': None,
            'd99_gy_openkbp': None,
            'd1_gy_openkbp': None,
            'v20gy_percent': float(100.0 * np.mean(values >= 20.0)),
            'note': 'Descriptive deterministic synthetic-phantom summaries only. Values use arbitrary synthetic scale units; they are not physically calibrated Gy, benchmark evaluator metrics, or clinical interpretations.',
        },
        'curve': [{'dose_gy': float(t), 'volume_percent': float(100.0 * np.mean(values >= t))} for t in thresholds],
        'method': 'Deterministic analytic water-cylinder phantom with a spherical target, two axial cylindrical OAR masks, and smooth Gaussian-like radial dose falloff; generated by MEDFORGE synthetic phantom v1.',
        'dose_sha256': volume_sha256('dose'),
        'roi_sha256': volume_sha256(roi),
    }


def roi_volume(roi: str) -> dict:
    mask = volume(roi).astype(bool, copy=False)
    indices = np.flatnonzero(mask).astype(np.uint32, copy=False)
    return {
        'source_file': f'{roi}.synthetic-mask',
        'source_sha256': volume_sha256(roi),
        'voxel_count': int(indices.size),
        'voxel_indices_c_order': indices.tolist(),
    }
